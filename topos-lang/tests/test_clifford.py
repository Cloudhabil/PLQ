"""Unit tests for Clifford Algebra and Geometric Native Coding engine."""

import math
import unittest
from topos.core.clifford import CliffordSignature, Multivector, PGA301, CGA410, STA130, EGA300


class TestCliffordAlgebra(unittest.TestCase):
    """Verifies multivector arithmetic, geometric product, reversion, and PGA motors."""

    def test_pga_signature_and_dimensions(self) -> None:
        self.assertEqual(PGA301.total_dim, 4)
        self.assertEqual(PGA301.multivector_dim, 16)
        self.assertEqual(PGA301.metric, (0, 1, 1, 1))

    def test_basis_products_pga(self) -> None:
        # e0^2 == 0
        e0 = Multivector.basis(PGA301, 1)  # e0 is bit 0 -> mask 1
        e0_sq = e0 * e0
        self.assertTrue(all(abs(c) < 1e-12 for c in e0_sq.components))

        # e1^2 == 1, e2^2 == 1, e3^2 == 1
        e1 = Multivector.basis(PGA301, 2)  # e1 is bit 1 -> mask 2
        e2 = Multivector.basis(PGA301, 4)  # e2 is bit 2 -> mask 4
        e1_sq = e1 * e1
        self.assertAlmostEqual(e1_sq.components[0], 1.0)
        self.assertTrue(all(abs(c) < 1e-12 for c in e1_sq.components[1:]))

        # e1 * e2 == -e2 * e1
        e1e2 = e1 * e2
        e2e1 = e2 * e1
        sum_anti = e1e2 + e2e1
        self.assertTrue(all(abs(c) < 1e-12 for c in sum_anti.components))

    def test_reversion_involution(self) -> None:
        # For grade 0: sign +1
        s = Multivector.scalar(PGA301, 3.5)
        self.assertEqual(s.reverse().components[0], 3.5)

        # For grade 1: sign +1
        e1 = Multivector.basis(PGA301, 2)
        self.assertEqual(e1.reverse().components[2], 1.0)

        # For grade 2: e12.reverse() == -e12 (k=2 -> 2*1//2 = 1 -> -1)
        e12 = Multivector.from_named_blades(PGA301, {"e1e2": 1.0})
        self.assertEqual(e12.reverse().get_blade("e1e2"), -1.0)

        # For grade 3: e123.reverse() == -e123 (k=3 -> 3*2//2 = 3 -> -1)
        e123 = Multivector.from_named_blades(PGA301, {"e1e2e3": 1.0})
        self.assertEqual(e123.reverse().get_blade("e1e2e3"), -1.0)

        # For grade 4: e0123.reverse() == +e0123 (k=4 -> 4*3//2 = 6 -> +1)
        e0123 = Multivector.from_named_blades(PGA301, {"e0e1e2e3": 1.0})
        self.assertEqual(e0123.reverse().get_blade("e0e1e2e3"), 1.0)

    def test_pga_rotor_sandwich_rotation(self) -> None:
        # Rotation around z-axis (in e1-e2 plane) by theta = pi/2
        theta = math.pi / 2
        # Generator B = -theta * e12
        e12 = Multivector.from_named_blades(PGA301, {"e1e2": 1.0})
        # Rotor R = exp(-0.5 * theta * e12) = cos(theta/2) - sin(theta/2) * e12
        rotor = Multivector.scalar(PGA301, math.cos(theta / 2)) - e12 * math.sin(theta / 2)

        # Vector along x-axis (e1)
        v_x = Multivector.from_named_blades(PGA301, {"e1": 1.0})
        # Rotate: v' = R * v * ~R
        v_rot = v_x.sandwich(rotor)

        # In 3D PGA plane-based / point-based:
        # e1 rotated by 90 deg in e1-e2 plane points to e2
        self.assertAlmostEqual(v_rot.get_blade("e1"), 0.0, places=7)
        self.assertAlmostEqual(v_rot.get_blade("e2"), 1.0, places=7)
        self.assertAlmostEqual(v_rot.get_blade("e3"), 0.0, places=7)

    def test_pga_motor_exp_translation(self) -> None:
        # In PGA, translation motor is generated by ideal line (bivector containing e0)
        # e.g., B = d * e01 (where e01^2 == 0)
        # exp(0.5 * B) = 1 + 0.5 * d * e01 exactly!
        d = 2.0
        e01 = Multivector.from_named_blades(PGA301, {"e0e1": 1.0})
        bivector = e01 * (0.5 * d)
        motor = bivector.exp_motor()

        self.assertAlmostEqual(motor.components[0], 1.0)
        self.assertAlmostEqual(motor.get_blade("e0e1"), 1.0)

    def test_standardized_pga301_motor(self) -> None:
        from topos.core.clifford import PGA301Motor
        # Motor with rotation 90 deg around z-axis and translation (1, 2, 3)
        motor = PGA301Motor.from_axis_angle_translation(
            axis=(0.0, 0.0, 1.0),
            angle=math.pi / 2,
            translation=(1.0, 2.0, 3.0),
        )
        # Check unit motor constraint M * ~M == 1
        self.assertTrue(motor.is_unit_motor())


if __name__ == "__main__":
    unittest.main()

