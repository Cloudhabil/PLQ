    def _emit_bakry_emery(
        self,
        cert: Optional[BakryEmeryCertificate],
        n: int,
    ) -> List[str]:
        """
        v3: FaddeevPopovAnomaly is opaque.
        EffectiveRicciCurvature := classicalBound - FPAnomaly.
        AnomalyScreeningHypothesis bounds the anomaly from above (not just existence of κ).
        Proof by linarith from the subtraction inequality.
        """
        kappa = cert.ricci_lower_bound_kappa if cert else 0.1875

        def _rat(x: float, denom: int = 10_000) -> str:
            num = round(x * denom)
            return f"({num} : ℝ) / {denom}"

        kappa_rat = _rat(kappa)
        kappa_f = f"{kappa:.10f}"

        return [
            "/-! ## §4  Bakry–Émery Curvature & Anomaly Screening -/",
            "",
            f"-- Classical Ricci lower bound on A/G: κ₀ = C₂(SU({n}))/(2β) ≈ {kappa_f}",
            f"def classicalRicciLowerBound : ℝ := {kappa_rat}",
            "",
            "/-- The Faddeev–Popov functional determinant trace anomaly at UV scale a.",
            "    Represents Tr(δ²/δA² log det(−D*D)).  Declared opaque: its value",
            "    in four dimensions requires the full non-perturbative analysis. -/",
            "opaque FaddeevPopovAnomaly (a : ℝ) : ℝ",
            "",
            "/-- The effective Bakry–Émery Ricci curvature of A/G at scale a.",
            "    Subtracts the trace anomaly from the classical lower bound. -/",
            "noncomputable def EffectiveRicciCurvature (a : ℝ) : ℝ :=",
            "  classicalRicciLowerBound - FaddeevPopovAnomaly a",
            "",
            "/-- Anomaly Screening Hypothesis (open in 4D Yang–Mills):",
            "    Non-perturbative screening prevents the trace anomaly from",
            "    overwhelming the classical curvature as a → 0.              ",
            "    Reference: Driver (1994) in 2D; fully open in 4D. -/",
            "def AnomalyScreeningHypothesis : Prop :=",
            "  ∃ (κ_floor : ℝ), 0 < κ_floor ∧",
            "    ∀ (a : ℝ), 0 < a → a < 1 →",
            "      FaddeevPopovAnomaly a ≤ classicalRicciLowerBound - κ_floor",
            "",
            "/-- Under the Anomaly Screening Hypothesis, the Bakry–Émery spectral gap",
            "    survives the continuum limit uniformly.",
            "    Proved by linarith on the arithmetic of the curvature subtraction. -/",
            "theorem bakry_emery_gap_continuum_limit",
            "    (h_screen : AnomalyScreeningHypothesis) :",
            "    ∃ (κ : ℝ), 0 < κ ∧",
            "      ∀ (a : ℝ), 0 < a → a < 1 → EffectiveRicciCurvature a ≥ κ := by",
            "  obtain ⟨κ_floor, h_pos, h_bound⟩ := h_screen",
            "  refine ⟨κ_floor, h_pos, ?_⟩",
            "  intro a ha_pos ha_lt",
            "  have h_anom := h_bound a ha_pos ha_lt",
            "  unfold EffectiveRicciCurvature",
            "  linarith",
            "",
        ]

