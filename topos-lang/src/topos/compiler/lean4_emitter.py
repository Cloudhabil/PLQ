    def _emit_multiscale_rg_induction(self) -> List[str]:
        """
        v3 NEW SECTION — replaces the v1/v2 circular ForwardInvarianceHypothesis
        (which assumed ∀a, gap(a) ≥ Δm with no mechanism).

        Instead, we formalise the Bałaban block-spin step as a single opaque
        transition `RG_Step : RGState → RGState`, and prove by structural induction
        on ℕ that if one step preserves the invariant region, all steps do.

        This is the mathematically correct formulation of Chapter 16.5 of the
        monograph: the induction base is the UV initial condition s₀, and the
        inductive step is the single-step forward invariance.
        """
        return [
            "/-! ## §5  Bałaban Multiscale RG Induction -/",
            "",
            "/-- State of the effective action at one RG scale. -/",
            "structure RGState where",
            "  scale_index  : ℕ",
            "  coupling     : ℝ",
            "  spectral_gap : ℝ",
            "",
            "/-- The Bałaban invariant region I(Δm):",
            "    coupling is strictly positive and spectral gap is bounded below by Δm. -/",
            "def InvariantRegion (s : RGState) (Δm : ℝ) : Prop :=",
            "  0 < s.coupling ∧ s.spectral_gap ≥ Δm",
            "",
            "/-- The discrete block-spin coarse-graining step R : S → S.",
            "    Declared opaque: its analytical definition requires the full",
            "    Bałaban integration-by-parts and polymer expansion. -/",
            "opaque RG_Step : RGState → RGState",
            "",
            "/-- Iterated renormalization group flow: n block-spin steps from s₀. -/",
            "def IteratedRG : ℕ → RGState → RGState",
            "  | 0,     s => s",
            "  | n + 1, s => RG_Step (IteratedRG n s)",
            "",
            "/-- Single-Step Forward Invariance (Monograph §16.5):",
            "    The RG block-spin transformation maps the invariant domain into itself.",
            "    This is the analytical content of Bałaban's theorem; it is left as",
            "    a named hypothesis because establishing it requires the full polymer",
            "    cluster expansion and interpolation estimates. -/",
            "def SingleStepForwardInvariance (Δm : ℝ) : Prop :=",
            "  ∀ (s : RGState), InvariantRegion s Δm → InvariantRegion (RG_Step s) Δm",
            "",
            "/-- Multiscale induction: if one step preserves I(Δm), then all n steps do.",
            "    Proved by structural induction on ℕ — no sorry, no circular hypothesis. -/",
            "theorem multiscale_balaban_induction",
            "    (Δm : ℝ)",
            "    (h_step : SingleStepForwardInvariance Δm)",
            "    (s₀ : RGState)",
            "    (h_init : InvariantRegion s₀ Δm) :",
            "    ∀ (n : ℕ), InvariantRegion (IteratedRG n s₀) Δm := by",
            "  intro n",
            "  induction n with",
            "  | zero   => exact h_init",
            "  | succ k ih => exact h_step (IteratedRG k s₀) ih",
            "",
            "/-- Corollary: the spectral gap is bounded below by Δm at every RG scale. -/",
            "theorem multiscale_gap_preserved",
            "    (Δm : ℝ)",
            "    (h_step : SingleStepForwardInvariance Δm)",
            "    (s₀ : RGState)",
            "    (h_init : InvariantRegion s₀ Δm) :",
            "    ∀ (n : ℕ), (IteratedRG n s₀).spectral_gap ≥ Δm := by",
            "  intro n",
            "  exact (multiscale_balaban_induction Δm h_step s₀ h_init n).2",
            "",
        ]

