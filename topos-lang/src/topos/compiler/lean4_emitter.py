    # ------------------------------------------------------------------

    def _emit_gauge_invariance_structural(self, n: int) -> List[str]:
        """
        v3 FIX: Eliminate `axiom elitzur_theorem` from v2.
        An axiom with conclusion `w.is_closed` for ALL w : WilsonLoop is unsound if
        WilsonLoop contains a mutable Prop field — a user can construct an open loop
        and then derive `False` via the axiom.

        Instead, `is_closed : IsCycle V E d1 chain` is a STRUCTURAL field of WilsonLoop.
        The constructor cannot be called without a proof of closure.  Gauge invariance
        then follows by `w.is_closed` — which is just field projection, not an axiom.
        """
        return [
            "/-! ## §2  Gauge Invariance as a Type Invariant (Elitzur's Principle) -/",
            "",
            "/-- A 1-chain: integer coefficients on oriented edges. -/",
            "abbrev Chain1 (E : ℕ) := Fin E → ℤ",
            "",
            "/-- A cycle: a chain whose discrete boundary vanishes.  ∂₁ c = 0. -/",
            "def IsCycle (V E : ℕ) (d1 : BMatrix V E) (c : Chain1 E) : Prop :=",
            "  d1.mulVec c = 0",
            "",
            "/-- WilsonLoop: structurally enforces gauge invariance.",
            "    `is_closed` is a FIELD, not a theorem — the type cannot be instantiated",
            "    without providing a proof that the boundary of `chain` vanishes.",
            "    This eliminates the v2 unsound axiom which permitted open loops.",
            f"    `gauge_N` records the SU({n}) rank. -/",
            "structure WilsonLoop (V E : ℕ) (d1 : BMatrix V E) where",
            "  loop_id   : String",
            f"  gauge_N   : ℕ := {n}",
            "  chain     : Chain1 E",
            "  is_closed : IsCycle V E d1 chain",
            "",
            "/-- Gauge invariance: follows directly from the structural field. -/",
            "theorem wilson_loop_is_gauge_invariant",
            "    (V E : ℕ) (d1 : BMatrix V E) (w : WilsonLoop V E d1) :",
            "    d1.mulVec w.chain = 0 :=",
            "  w.is_closed",
            "",
        ]

